CREATE TABLE public.report_branding (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  letterhead_path text,
  footer_text text NOT NULL DEFAULT 'Generated by LNPATS ERP System | Liberia National Police Academy & Training School | Confidential Official Document',
  updated_by uuid,
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.report_branding TO authenticated;
GRANT INSERT, UPDATE ON public.report_branding TO authenticated;
GRANT ALL ON public.report_branding TO service_role;
ALTER TABLE public.report_branding ENABLE ROW LEVEL SECURITY;
CREATE POLICY report_branding_read ON public.report_branding FOR SELECT TO authenticated USING (true);
CREATE POLICY report_branding_admin_insert ON public.report_branding FOR INSERT TO authenticated WITH CHECK (public.has_role(auth.uid(), 'system_admin'));
CREATE POLICY report_branding_admin_update ON public.report_branding FOR UPDATE TO authenticated USING (public.has_role(auth.uid(), 'system_admin')) WITH CHECK (public.has_role(auth.uid(), 'system_admin'));
CREATE TRIGGER audit_report_branding AFTER INSERT OR UPDATE OR DELETE ON public.report_branding FOR EACH ROW EXECUTE FUNCTION public.audit_trigger();
INSERT INTO public.report_branding (id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE public.report_numbers (
  day date PRIMARY KEY,
  last_no integer NOT NULL DEFAULT 0
);
GRANT ALL ON public.report_numbers TO service_role;
ALTER TABLE public.report_numbers ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.next_report_number()
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE d date := (now() AT TIME ZONE 'Africa/Monrovia')::date; n integer;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not signed in'; END IF;
  INSERT INTO public.report_numbers(day, last_no) VALUES (d, 1)
  ON CONFLICT (day) DO UPDATE SET last_no = report_numbers.last_no + 1 RETURNING last_no INTO n;
  RETURN 'LNPATS-RPT-' || to_char(d, 'YYYYMMDD') || '-' || lpad(n::text, 4, '0');
END $$;
REVOKE ALL ON FUNCTION public.next_report_number() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.next_report_number() TO authenticated;

