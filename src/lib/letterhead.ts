import letterheadBanner from '@/assets/lnpats-letterhead.png.asset.json';
/** Built-in official letterhead banner; System Administrators may replace it centrally (report_branding). */
export const letterheadUrl = letterheadBanner.url;
export const LETTERHEAD_RATIO = 270 / 1175;
export const DEFAULT_FOOTER = 'Generated by LNPATS ERP System | Liberia National Police Academy & Training School | Confidential Official Document';

export type Branding = { url: string; footer: string };
let brandingCache: Promise<Branding> | null = null;
export function clearBrandingCache() { brandingCache = null; }
/** Centralized letterhead configuration used by every report template. */
export function getBranding(): Promise<Branding> {
  brandingCache ??= (async () => {
    const { data } = await supabase.from('report_branding').select('letterhead_path, footer_text').eq('id', 1).maybeSingle();
    let url = letterheadUrl;
    if (data?.letterhead_path) {
      const s = await supabase.storage.from('branding').createSignedUrl(data.letterhead_path, 3600);
      if (s.data?.signedUrl) url = s.data.signedUrl;
    }
    return { url, footer: data?.footer_text || DEFAULT_FOOTER };
  })().catch(() => ({ url: letterheadUrl, footer: DEFAULT_FOOTER }));
  return brandingCache;
}

/** Auto-generated report number (LNPATS-RPT-YYYYMMDD-NNNN, Liberia date). */
export async function nextReportNumber() {
  const { data } = await supabase.rpc('next_report_number');
  return (data as string | null) ?? `LNPATS-RPT-${Date.now()}`;
}

type PdfLike = { internal: { pageSize: { getWidth(): number; getHeight(): number } }; addImage: (...a: never[]) => unknown };
/** Loads the letterhead once; returns a painter that draws it (scaled to page width — A4, Letter or Legal) and the y below it. */
export async function pdfLetterhead() {
  const b = await getBranding();
  const data = await imageDataUrl(b.url).catch(() => null);
  const draw = (doc: PdfLike, top = 4) => {
    const w = doc.internal.pageSize.getWidth();
    const imgW = Math.min(w - 16, 260), imgH = imgW * LETTERHEAD_RATIO;
    if (data) (doc.addImage as unknown as (d: string, f: string, x: number, y: number, w: number, h: number, a?: string, c?: string) => void)(data, 'PNG', (w - imgW) / 2, top, imgW, imgH, 'letterhead', 'NONE');
    return top + imgH + 2;
  };
  return { draw, data, footer: b.footer };
}
export async function drawPdfLetterhead(doc: PdfLike, top = 4) { return (await pdfLetterhead()).draw(doc, top); }
